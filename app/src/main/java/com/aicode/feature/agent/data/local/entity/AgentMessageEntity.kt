package com.aicode.feature.agent.data.local.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.aicode.feature.agent.presentation.AgentAttachment
import com.aicode.feature.agent.presentation.BACKGROUND_NOTIFICATION_PREFIX
import com.aicode.feature.agent.presentation.COMPACTION_FAILURE_TOOL_NAME
import com.aicode.feature.agent.presentation.MessageRole
import com.aicode.feature.agent.presentation.AgentUIMessage
import kotlinx.serialization.decodeFromString
import kotlinx.serialization.json.Json

@Entity(
    tableName = "agent_messages",
    indices = [Index(value = ["sessionId"])]
)
data class AgentMessageEntity(
    @PrimaryKey val id: String,
    val sessionId: String,
    val role: String,
    val content: String,
    val timestamp: Long,
    // ASSISTANT rows only: structured tool_calls (a Json-encoded List<ToolCall>), null when there are no tool calls.
    val toolCallsJson: String? = null,
    // TOOL rows only: the id of the corresponding assistant tool_use, used to rebuild a valid pairing on replay.
    val toolCallId: String? = null,
    // TOOL rows only: the tool name, for UI rendering.
    val toolName: String? = null,
    // TOOL rows only: the arguments passed to this call (argsPreview, JSON text), used by the UI to show "the executed command".
    val toolArgs: String? = null,
    // TOOL rows only: whether the tool execution failed, used by the UI to render the status dot (green/red).
    val isError: Boolean = false,
    // ASSISTANT rows only: the reasoning process of the model this turn (reasoning). Persisted for UI display; when Anthropic thinking is enabled, it is sent back verbatim together with signature. Null when absent.
    val reasoning: String? = null,
    // ASSISTANT rows only: the encrypted signature for Anthropic extended thinking. Sent back together with reasoning (required in the tool loop), otherwise 400. Null for other providers.
    val signature: String? = null,
    // USER rows only: display metadata for attachments uploaded by the user. The internal model prompt still does not go into content.
    val attachmentsJson: String? = null,
    /** This message has been folded into a summary by context compaction and should no longer take part in context replay or UI display. Defaults to false. */
    val isCompacted: Boolean = false,
    /** Internal summary generated by context compaction: takes part in model replay, but is not shown as a normal chat bubble. */
    val isContextSummary: Boolean = false,
    /** Internal user anchor generated by context compaction: takes part in model replay, and the UI renders it as a compaction divider. */
    val isCompactionMarker: Boolean = false,
    val inputTokens: Int = 0,
    val outputTokens: Int = 0,
    // ASSISTANT rows only: verbatim snapshot of the Anthropic thinking / redacted_thinking content blocks (JSON array text).
    // The documentation requires these blocks to be sent back unmodified and in their original order, so the original blocks are stored rather than split into fields (redacted data cannot be reconstructed).
    // Position at the end: the backup DTO mapping uses positional arguments, so inserting in the middle would misalign it.
    val thinkingBlocksJson: String? = null,
    // ASSISTANT rows only: the number of tokens in this turn's input that hit the server-side cache; the UI uses this to show the cache hit rate. Likewise, it can only be appended at the end.
    val cachedInputTokens: Int = 0,
    @ColumnInfo(defaultValue = "0")
    val isContextExcluded: Boolean = false,
    val compactedBySummaryId: String? = null
) {
    fun toUIMessage(): AgentUIMessage {
        val roleEnum = MessageRole.valueOf(role)
        return AgentUIMessage(
            id = id,
            role = roleEnum,
            content = content,
            timestamp = timestamp,
            toolName = toolName,
            toolArgs = toolArgs,
            isError = isError,
            reasoning = reasoning,
            attachments = decodeAttachments(attachmentsJson),
            isCompactionMarker = isCompactionMarker,
            isContextSummary = isContextSummary,
            isCompactionFailure = roleEnum == MessageRole.TOOL && toolName == COMPACTION_FAILURE_TOOL_NAME,
            isBackgroundNotification = roleEnum == MessageRole.USER &&
                content.startsWith(BACKGROUND_NOTIFICATION_PREFIX),
            inputTokens = inputTokens,
            outputTokens = outputTokens,
            cachedInputTokens = cachedInputTokens
        )
    }

    private fun decodeAttachments(value: String?): List<AgentAttachment> {
        if (value.isNullOrBlank()) return emptyList()
        return runCatching { json.decodeFromString<List<AgentAttachment>>(value) }.getOrDefault(emptyList())
    }

    private companion object {
        val json = Json { ignoreUnknownKeys = true }
    }
}
